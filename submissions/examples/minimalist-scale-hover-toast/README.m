## 🚀 Usage

1. Open `demo.html` in a modern web browser.
2. Hover over a toast notification to see the scale-hover effect.
3. Customize the icons, colors, messages, and spacing to suit your project.
4. Modify the CSS custom properties to match your design system.

---

## 🎨 CSS Custom Properties

| Variable | Description |
|----------|-------------|
| `--bg` | Page background color |
| `--surface` | Toast background |
| `--success` | Success accent color |
| `--warning` | Warning accent color |
| `--info` | Information accent color |
| `--text` | Primary text color |
| `--muted` | Secondary text color |
| `--border` | Border color |
| `--radius` | Toast border radius |
| `--shadow` | Toast shadow |
| `--transition` | Transition timing |

Example:

```css
:root{
    --success:#16a34a;
    --warning:#f59e0b;
    --info:#2563eb;
}
```

