# CSS Scale-Hover Toast

A modern **CSS Scale-Hover Toast** built entirely with **HTML5** and **CSS3**. This showcase demonstrates lightweight toast notifications with a smooth scale-on-hover interaction, responsive layout, and accessibility support—all without JavaScript.

---

## ✨ Features

- 🚀 Pure HTML5 & CSS3
- 🔍 Smooth scale-hover interaction
- ✅ Success toast variant
- ⚠️ Warning toast variant
- ℹ️ Information toast variant
- 💻 Minimalist tech-inspired design
- 📱 Fully responsive layout
- ♿ Accessible with `role="status"` and `aria-live="polite"`
- 🎨 Easy customization using CSS Custom Properties
- 🌙 Supports `prefers-reduced-motion`
- ⚙️ No JavaScript or external libraries

